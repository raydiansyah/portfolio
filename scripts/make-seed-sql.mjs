#!/usr/bin/env node
/**
 * Generate the content seed migration from src/features/harbor/data/content.ts
 * so the database starts with exactly what the static site showed.
 * Usage: node scripts/make-seed-sql.mjs > supabase/migrations/<ts>_seed_site_content.sql
 * Idempotent SQL: re-running inserts nothing that already exists.
 */
const { PROJECTS, SERVICES, ABOUT } = await import('../src/features/harbor/data/content.ts')

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`)
const arr = (a) => `array[${a.map(q).join(', ')}]::text[]`

const CATEGORY = {
  'Interactive Learning Platform': 'Web', 'Certification Platform': 'Web', 'Omnichannel Commerce': 'Web',
  'Management Platform': 'Web', 'Mobile Application': 'Mobile', 'IT Training': 'Training', 'Open Source': 'Open Source',
}
const SERVICE_ICONS = ['Globe', 'Sparkles', 'GraduationCap', 'Compass']
const SKILL_CATEGORY = {
  TypeScript: 'frontend', React: 'frontend', 'Next.js': 'frontend', 'Three.js': 'frontend',
  Laravel: 'backend', 'Node.js': 'backend', MySQL: 'backend', PostgreSQL: 'backend', Docker: 'devops',
}
const SKILL_LEVEL = [92, 90, 85, 88, 82, 80, 78, 70, 65]

const out = []
out.push('-- Seed: initial site content (generated by scripts/make-seed-sql.mjs from content.ts).')
out.push('-- Idempotent: portfolios/services/skills are only inserted when missing.\n')

out.push('insert into public.portfolios (slug, title, category, summary, description, tech_stack, live_url, repo_url, status, featured, order_index, published_at) values')
out.push(PROJECTS.map((p, i) => `  (${[q(p.id), q(p.title), q(CATEGORY[p.category] ?? 'Web'), q(p.summary), q(p.description), arr(p.stack),
  q(p.liveUrl), q(p.repoUrl), "'published'", p.featured, i, `make_date(${p.year}, 1, 1)::timestamptz`].join(', ')})`).join(',\n'))
out.push('on conflict (slug) do nothing;\n')

out.push('insert into public.services (icon, name, description, is_active, order_index)')
out.push('select v.icon, v.name, v.description, true, v.ord from (values')
out.push(SERVICES.map((s, i) => `  (${q(SERVICE_ICONS[i] ?? 'Globe')}, ${q(s.title)}, ${q(s.summary)}, ${i})`).join(',\n'))
out.push(') as v(icon, name, description, ord)')
out.push('where not exists (select 1 from public.services x where x.name = v.name);\n')

out.push('insert into public.skills (name, category, level, order_index)')
out.push('select v.name, v.category::public.skill_category, v.level, v.ord from (values')
out.push(ABOUT.stack.map((n, i) => `  (${q(n)}, ${q(SKILL_CATEGORY[n] ?? 'other')}, ${SKILL_LEVEL[i] ?? 60}, ${i})`).join(',\n'))
out.push(') as v(name, category, level, ord)')
out.push('where not exists (select 1 from public.skills x where x.name = v.name);\n')

out.push("update public.settings set site_name = 'Ray Diansyah — Harbor' where id = 1 and site_name = 'Ray Diansyah';")
console.log(out.join('\n'))
